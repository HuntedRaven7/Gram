const std = @import("std");
const console = @import("console.zig");

const unit_path = "/usr/lib/systemd/system/gram-installer.service";
const console_path = "/sys/class/tty/console/active";
const dropin_name = "gram-installer.service.d/10-console.conf";

pub const Paths = struct {
    output_dir: []const u8,
    early_dir: ?[]const u8,
    unit: []const u8,
    console: []const u8,
};

fn readFile(io: std.Io, allocator: std.mem.Allocator, path: []const u8) ![]u8 {
    return std.Io.Dir.cwd().readFileAlloc(io, path, allocator, .unlimited);
}

fn hasTtyPath(unit: []const u8) bool {
    var lines = std.mem.splitScalar(u8, unit, '\n');
    while (lines.next()) |line| {
        if (std.mem.startsWith(u8, line, "TTYPath=")) return true;
    }
    return false;
}

pub fn generate(io: std.Io, allocator: std.mem.Allocator, paths: Paths) !void {
    const unit = readFile(io, allocator, paths.unit) catch return;
    // The headless CI unit has no TTYPath and uses journal stdio. Leave it alone.
    if (!hasTtyPath(unit)) return;

    const active = readFile(io, allocator, paths.console) catch return;
    const serial = console.serialConsole(active) orelse return;

    const dir = try std.fs.path.join(allocator, &.{ paths.output_dir, "gram-installer.service.d" });
    try std.Io.Dir.cwd().createDirPath(io, dir);
    const content = try std.fmt.allocPrint(
        allocator,
        "# Generated by gram-installer-console-generator from {s}\n" ++
            "[Unit]\nSourcePath={s}\n\n" ++
            "[Service]\nTTYPath=/dev/{s}\nTTYRows=24\nTTYColumns=80\n",
        .{ paths.console, paths.console, serial },
    );
    const path = try std.fs.path.join(allocator, &.{ dir, "10-console.conf" });
    try std.Io.Dir.cwd().writeFile(io, .{ .sub_path = path, .data = content });

    // systemd also starts a getty on the serial console. Mask it in the live
    // root so it cannot take the tty back from the installer TUI.
    if (paths.early_dir) |early_dir| {
        try std.Io.Dir.cwd().createDirPath(io, early_dir);
        const getty = try std.fmt.allocPrint(allocator, "serial-getty@{s}.service", .{serial});
        const link = try std.fs.path.join(allocator, &.{ early_dir, getty });
        try std.Io.Dir.cwd().symLinkAtomic(io, "/dev/null", link, .{});
    }
}

pub fn main(init: std.process.Init) !void {
    const allocator = init.arena.allocator();
    var args = std.process.Args.Iterator.init(init.minimal.args);
    defer args.deinit();
    _ = args.next();
    const output_dir = args.next() orelse return;
    try generate(init.io, allocator, .{
        .output_dir = output_dir,
        .early_dir = args.next(),
        .unit = unit_path,
        .console = console_path,
    });
}

const Fixture = struct {
    tmp: std.testing.TmpDir,
    paths: Paths,
};

fn fixture(allocator: std.mem.Allocator, unit: []const u8, active: []const u8) !Fixture {
    const tmp = std.testing.tmpDir(.{});
    const base = try std.fmt.allocPrint(allocator, ".zig-cache/tmp/{s}", .{tmp.sub_path});
    const unit_file = try std.fs.path.join(allocator, &.{ base, "gram-installer.service" });
    const console_file = try std.fs.path.join(allocator, &.{ base, "active" });
    const output_dir = try std.fs.path.join(allocator, &.{ base, "generator" });
    const early_dir = try std.fs.path.join(allocator, &.{ base, "generator.early" });
    try std.Io.Dir.cwd().writeFile(std.testing.io, .{ .sub_path = unit_file, .data = unit });
    try std.Io.Dir.cwd().writeFile(std.testing.io, .{ .sub_path = console_file, .data = active });
    return .{ .tmp = tmp, .paths = .{
        .output_dir = output_dir,
        .early_dir = early_dir,
        .unit = unit_file,
        .console = console_file,
    } };
}

fn readDropin(allocator: std.mem.Allocator, paths: Paths) ![]u8 {
    const path = try std.fs.path.join(allocator, &.{ paths.output_dir, dropin_name });
    return std.Io.Dir.cwd().readFileAlloc(std.testing.io, path, allocator, .unlimited);
}

fn gettyMaskExists(allocator: std.mem.Allocator, paths: Paths, name: []const u8) !bool {
    const path = try std.fs.path.join(allocator, &.{ paths.early_dir.?, name });
    var buffer: [64]u8 = undefined;
    const len = std.Io.Dir.cwd().readLink(std.testing.io, path, &buffer) catch return false;
    return std.mem.eql(u8, buffer[0..len], "/dev/null");
}

test "generator writes the serial tty and geometry drop-in" {
    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();
    const allocator = arena.allocator();
    var f = try fixture(allocator, "[Service]\nTTYPath=/dev/tty1\n", "tty0 ttyS0\n");
    defer f.tmp.cleanup();

    try generate(std.testing.io, allocator, f.paths);

    const content = try readDropin(allocator, f.paths);
    try std.testing.expect(std.mem.indexOf(u8, content, "TTYPath=/dev/ttyS0") != null);
    try std.testing.expect(std.mem.indexOf(u8, content, "TTYRows=24") != null);
    try std.testing.expect(std.mem.indexOf(u8, content, "TTYColumns=80") != null);
    try std.testing.expect(try gettyMaskExists(allocator, f.paths, "serial-getty@ttyS0.service"));
}

test "generator keeps the tty1 default on a virtual console" {
    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();
    const allocator = arena.allocator();
    var f = try fixture(allocator, "[Service]\nTTYPath=/dev/tty1\n", "tty0\n");
    defer f.tmp.cleanup();

    try generate(std.testing.io, allocator, f.paths);
    try std.testing.expectError(error.FileNotFound, readDropin(allocator, f.paths));
    try std.testing.expect(!try gettyMaskExists(allocator, f.paths, "serial-getty@ttyS0.service"));
}

test "generator leaves the headless unit untouched" {
    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();
    const allocator = arena.allocator();
    var f = try fixture(allocator, "[Service]\nStandardInput=null\n", "tty0 ttyS0\n");
    defer f.tmp.cleanup();

    try generate(std.testing.io, allocator, f.paths);
    try std.testing.expectError(error.FileNotFound, readDropin(allocator, f.paths));
    try std.testing.expect(!try gettyMaskExists(allocator, f.paths, "serial-getty@ttyS0.service"));
}
